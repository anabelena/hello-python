def suma(numero1,numero2):
    """
    La funcion realiza una sumatoria de dos numeros enteros.
    
    Argumentos:
    numero1 (int)
    numero2 (int)

    Se retorna la suma de los parametros.

    >>> suma(5,6)
    11

    >>> suma(10,20)
    30

    """
    return numero1 + numero2

