"""
Tipado Dinamico: La posibilidad que tienen las variables de almacenar 
diferentes tipos de datos en diferentes momentos.
"""
valor = 'Eduardo'
tipo = type(valor)
print(tipo)

valor = 2
tipo = type(valor)
print(tipo)

valor = 3.1
tipo = type(valor)
print(tipo)

valor = True

print(valor)

#TIPOS DE DATOS utilizando funcion type()

tipo = type(valor)

print(type(valor))


