#Operadores Relacionales o Logicos
#Nos permiten comparar tipos de datos NUMERICOS y nos retornan un valor Booleano
#Nos permiten implementar condiciones entre dos valores
numero_uno = 10
numero_dos = 10

""" 
>
<
>=
<=
==
!=
"""
resutado = numero_uno > numero_dos
print(resutado)

resutado = numero_uno < numero_dos
print(resutado)

resutado = numero_uno >= numero_dos
print(resutado)

#La variable Resultado sera de tipo booleano

resultado = numero_dos == numero_uno
print(resultado)

